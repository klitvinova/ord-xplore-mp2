-- Migration 001: TEI tag inventory
--
-- The original dashboard kept tag membership in a client-side JSON blob
-- (tag_presence_optimized.json), keyed by an index into file_index.json.
-- That index does not correspond to documents.id, so the custom tag filter
-- could not survive the move to SQL. These two tables give tags a first-class
-- home in the database.
--
-- Apply with:
--   psql -d ord_xplore -v ON_ERROR_STOP=1 -f db/001_add_tags.sql

BEGIN;

CREATE TABLE IF NOT EXISTS tags (
  id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name  VARCHAR(255) NOT NULL UNIQUE   -- TEI local name, no namespace prefix
);

CREATE TABLE IF NOT EXISTS document_tags (
  document_id  INTEGER NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
  tag_id       INTEGER NOT NULL REFERENCES tags(id)      ON DELETE RESTRICT,
  occurrences  INTEGER NOT NULL DEFAULT 1,
  PRIMARY KEY (document_id, tag_id)
);

-- The dashboard's hot path is "which documents carry tag X", so the tag_id
-- side needs its own index; the PK only covers the document_id side.
CREATE INDEX IF NOT EXISTS idx_document_tags_tag_id ON document_tags(tag_id);

COMMIT;
