-- Migration 003: Dynamic Properties and Values Catalog
--
-- Adds first-class dynamic properties and property value associations
-- compatible with the Metadata Curation Framework (MCF).
--
-- Apply with:
--   psql -d ord_xplore -v ON_ERROR_STOP=1 -f db/003_add_properties_and_values.sql

BEGIN;

CREATE TABLE IF NOT EXISTS properties (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         VARCHAR(255) NOT NULL UNIQUE,
  display_name VARCHAR(255) NOT NULL,
  type         VARCHAR(50) NOT NULL, -- 'binary', 'multiple_choice', 'numerical', 'datetime', 'free_text'
  description  TEXT,
  options      JSONB DEFAULT '[]'::jsonb,
  created_at   TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS edition_property_values (
  edition_id   INTEGER NOT NULL REFERENCES editions(id) ON DELETE CASCADE,
  property_id  INTEGER NOT NULL REFERENCES properties(id) ON DELETE CASCADE,
  value        JSONB NOT NULL,
  PRIMARY KEY (edition_id, property_id)
);

CREATE TABLE IF NOT EXISTS document_property_values (
  document_id  INTEGER NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
  property_id  INTEGER NOT NULL REFERENCES properties(id) ON DELETE CASCADE,
  value        JSONB NOT NULL,
  PRIMARY KEY (document_id, property_id)
);

CREATE INDEX IF NOT EXISTS idx_properties_name ON properties(name);
CREATE INDEX IF NOT EXISTS idx_edition_property_values_prop_id ON edition_property_values(property_id);
CREATE INDEX IF NOT EXISTS idx_edition_property_values_gin ON edition_property_values USING GIN (value);
CREATE INDEX IF NOT EXISTS idx_doc_property_values_prop_id ON document_property_values(property_id);
CREATE INDEX IF NOT EXISTS idx_doc_property_values_gin ON document_property_values USING GIN (value);

COMMIT;
