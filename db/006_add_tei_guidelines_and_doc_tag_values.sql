-- Migration 006: TEI Tag Guidelines & Document-Level Tag Values
--
-- 1. tei_tag_definitions: Reference catalog of TEI P5 elements with semantic descriptions & search mappings.
-- 2. document_tag_values: Document-level extracted values and attributes for granular search.
--
-- Apply with:
--   psql -d ord_xplore -v ON_ERROR_STOP=1 -f db/006_add_tei_guidelines_and_doc_tag_values.sql

BEGIN;

CREATE TABLE IF NOT EXISTS tei_tag_definitions (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name            VARCHAR(255) NOT NULL UNIQUE,
  category        VARCHAR(100) NOT NULL,
  description     TEXT NOT NULL,
  example_queries TEXT[] DEFAULT '{}'::text[],
  created_at      TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS document_tag_values (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id     INTEGER NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
  tag_name        VARCHAR(255) NOT NULL,
  attribute_name  VARCHAR(255),               -- NULL for inner text content, or attribute name like 'when', 'type', 'ref'
  value           TEXT NOT NULL,              -- Text content or attribute value
  occurrences     INTEGER NOT NULL DEFAULT 1,
  created_at      TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_tei_tag_def_name ON tei_tag_definitions(name);
CREATE INDEX IF NOT EXISTS idx_tei_tag_def_category ON tei_tag_definitions(category);

CREATE INDEX IF NOT EXISTS idx_doc_tag_values_doc_id ON document_tag_values(document_id);
CREATE INDEX IF NOT EXISTS idx_doc_tag_values_tag_name ON document_tag_values(tag_name);
CREATE INDEX IF NOT EXISTS idx_doc_tag_values_tag_val ON document_tag_values(tag_name, value);

COMMIT;
